export const getRandomMotivationalMessage = (): string => {
  const randomIndex = Math.floor(Math.random() * motivationalMessages.length);
  return motivationalMessages[randomIndex];
};

export const getMotivationalMessageByTime = (): string => {
  const hour = new Date().getHours();

  if (hour >= 6 && hour < 12) {
    const morningMessages = [
      "Доброе утро! Начни день с энергией 🌅",
      "Утро - идеальное время для фокуса",
      "Новый день, новые возможности",
      "Проснись и начни покорять мир",
      "Утренняя продуктивность - лучшая продуктивность",
    ];
    return morningMessages[Math.floor(Math.random() * morningMessages.length)];
  }

  if (hour >= 12 && hour < 18) {
    const afternoonMessages = [
      "Полдень - время для важных дел",
      "Ты уже в боевом режиме! 💪",
      "Продолжай, день еще молодой",
      "Послеобеденный фокус - это мощно",
      "Ты на пике своей продуктивности",
    ];
    return afternoonMessages[Math.floor(Math.random() * afternoonMessages.length)];
  }

  if (hour >= 18 && hour < 21) {
    const eveningMessages = [
      "Вечер - время завершить дела",
      "Финальный рывок к успеху",
      "Закончи день на высокой ноте",
      "Вечерняя сессия - это последний шанс",
      "Ты почти дома, финишируй сильно",
    ];
    return eveningMessages[Math.floor(Math.random() * eveningMessages.length)];
  }

  const nightMessages = [
    "Ночной сова? Ты молод! 🦉",
    "Ночь - время для глубокого фокуса",
    "Когда все спят, ты работаешь",
    "Ночная сессия - это посвящение",
    "Ты готов к челленджу? Начни сейчас",
  ];
  return nightMessages[Math.floor(Math.random() * nightMessages.length)];
};

export default motivationalMessages;